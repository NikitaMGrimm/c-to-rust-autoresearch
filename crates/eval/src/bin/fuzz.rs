//! Generates fuzzed inputs for every benchmark program by changing its own
//! inputs. An input is kept when the C program is a valid reference on it and
//! behaves unlike on every input kept so far, so each one can catch a
//! translation that the others miss. The evaluator reports separately whether
//! a passing translation also passes them. Development inputs go next to the
//! public programs, private ones next to theirs, and only counts are printed.

use std::collections::BTreeSet;
use std::os::unix::fs::DirBuilderExt;
use std::path::Path;
use std::process::ExitCode;

use eval::{Input, Rng};

const USAGE: &str = "usage: fuzz PRIVATE_DIR\n\
     Writes NAME.fuzz.json next to every program in bench/dev and in the\n\
     validation and held-out sets of PRIVATE_DIR. Run it after intake, which\n\
     removes them.";
/// Fuzzed inputs kept per program at most.
const KEEP: usize = 10;
/// Candidates tried per program.
const ATTEMPTS: usize = 200;
/// Each candidate on which the C program times out costs the full time
/// limit, so a program is given up after this many.
const TIMEOUTS: usize = 3;
/// Public, so the development inputs can be regenerated by anyone.
const SEED: u64 = 0x6675_7a7a;
/// Numbers at which integer handling often goes wrong.
const EDGES: [&str; 21] = [
    "0",
    "1",
    "-1",
    "2",
    "10",
    "127",
    "128",
    "-129",
    "255",
    "256",
    "32767",
    "-32769",
    "65535",
    "65536",
    "2147483647",
    "2147483648",
    "-2147483648",
    "-2147483649",
    "4294967295",
    "4294967296",
    "9223372036854775807",
];
/// Characters put into text, from the kinds that parsers treat differently.
const CHARACTERS: [char; 8] = ['a', 'Z', ' ', '-', '0', '.', ',', 'x'];
const REPO: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../..");

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let [private] = args.as_slice() else {
        eprintln!("{USAGE}");
        return ExitCode::from(2);
    };
    match generate(Path::new(private)) {
        Ok(()) => ExitCode::SUCCESS,
        Err(err) => {
            eprintln!("{err}");
            ExitCode::FAILURE
        }
    }
}

fn generate(private: &Path) -> Result<(), String> {
    let sets = [
        ("dev", Path::new(REPO).join("bench/dev")),
        ("validation", private.join("validation")),
        ("held-out", private.join("held-out")),
    ];
    // Private and new: a planted directory or symlink at this path must not be used.
    let scratch = std::env::temp_dir().join(format!("c2r-fuzz-{}", std::process::id()));
    std::fs::DirBuilder::new()
        .mode(0o700)
        .create(&scratch)
        .map_err(|err| format!("cannot create {}: {err}", scratch.display()))?;
    let result = sets.iter().try_for_each(|(set, dir)| {
        let programs = eval::c_programs(dir)?;
        let (mut fuzzed, mut inputs) = (0, 0);
        for c_file in &programs {
            let name = c_file.file_stem().unwrap_or_default().to_string_lossy();
            let kept = fuzz(c_file, &name, &scratch.join(set).join(name.as_ref()))?;
            let path = c_file.with_extension(eval::FUZZ_EXTENSION);
            if kept.is_empty() {
                match std::fs::remove_file(&path) {
                    Err(err) if err.kind() != std::io::ErrorKind::NotFound => {
                        return Err(format!("cannot remove {}: {err}", path.display()));
                    }
                    _ => {}
                }
            } else {
                write_inputs(&path, &kept)?;
                fuzzed += 1;
                inputs += kept.len();
            }
        }
        println!(
            "{set}: {inputs} inputs for {fuzzed} of {} programs",
            programs.len()
        );
        Ok(())
    });
    let _ = std::fs::remove_dir_all(&scratch);
    result
}

/// The fuzzed inputs of one program, in the order they were found.
fn fuzz(c_file: &Path, name: &str, work: &Path) -> Result<Vec<Input>, String> {
    std::fs::create_dir_all(work)
        .map_err(|err| format!("cannot create {}: {err}", work.display()))?;
    let spec = eval::spec(c_file)?;
    let references = eval::References::build(c_file, &spec.c_flags, work)
        .map_err(|err| format!("{}: {err}", c_file.display()))?;
    let behaviour = |run: eval::Run| (run.stdout, run.exit);
    let mut seen: BTreeSet<_> = spec
        .inputs
        .iter()
        .filter_map(|input| references.check(input).ok())
        .map(behaviour)
        .collect();
    let mut rng = Rng(eval::mix(SEED ^ eval::fnv(name)));
    let (mut kept, mut timeouts) = (Vec::new(), 0);
    for _ in 0..ATTEMPTS {
        if kept.len() == KEEP || timeouts == TIMEOUTS {
            break;
        }
        let original = &spec.inputs[rng.below(spec.inputs.len() as u64) as usize];
        let mut candidate = original.clone();
        for _ in 0..=rng.below(2) {
            mutate(&mut candidate, &mut rng);
        }
        let known = |input: &Input| input.args == candidate.args && input.stdin == candidate.stdin;
        if spec.inputs.iter().chain(&kept).any(known) {
            continue;
        }
        match references.check(&candidate) {
            Ok(run) => {
                if seen.insert(behaviour(run)) {
                    candidate.name = format!("fuzz_{}", kept.len() + 1);
                    kept.push(candidate);
                }
            }
            Err("c_timeout") => timeouts += 1,
            Err(_) => {}
        }
    }
    Ok(kept)
}

fn write_inputs(path: &Path, inputs: &[Input]) -> Result<(), String> {
    let inputs: Vec<_> = inputs
        .iter()
        .map(|input| {
            serde_json::json!({
                "name": input.name,
                "args": input.args,
                "stdin": String::from_utf8_lossy(&input.stdin),
            })
        })
        .collect();
    let json = serde_json::json!({ "inputs": inputs });
    std::fs::write(path, format!("{json:#}\n"))
        .map_err(|err| format!("cannot write {}: {err}", path.display()))
}

/// Applies one random change. A change that does not fit the input leaves it
/// as it was.
fn mutate(input: &mut Input, rng: &mut Rng) {
    match rng.below(4) {
        0 => change_number(input, rng),
        1 => change_args(input, rng),
        2 => change_stdin(input, rng),
        _ => change_character(input, rng),
    }
}

/// The arguments followed by standard input, which inputs from JSON always
/// hold as UTF-8.
fn texts(input: &Input) -> Vec<String> {
    let stdin = String::from_utf8_lossy(&input.stdin).into_owned();
    input.args.iter().cloned().chain([stdin]).collect()
}

fn set_texts(input: &mut Input, mut texts: Vec<String>) {
    input.stdin = texts.pop().unwrap_or_default().into_bytes();
    input.args = texts;
}

fn pick<T: Copy>(items: &[T], rng: &mut Rng) -> T {
    items[rng.below(items.len() as u64) as usize]
}

/// Replaces one number by an edge value, a neighbour or random digits.
fn change_number(input: &mut Input, rng: &mut Rng) {
    let mut texts = texts(input);
    let numbers: Vec<(usize, usize, usize)> = texts
        .iter()
        .enumerate()
        .flat_map(|(field, text)| {
            numbers(text)
                .into_iter()
                .map(move |(start, end)| (field, start, end))
        })
        .collect();
    if numbers.is_empty() {
        return;
    }
    let (field, start, end) = pick(&numbers, rng);
    let old = &texts[field][start..end];
    let new = match rng.below(4) {
        0 | 1 => pick(&EDGES, rng).to_owned(),
        2 => old.parse::<i128>().map_or_else(
            |_| "0".to_owned(),
            |n| (n + if rng.below(2) == 0 { 1 } else { -1 }).to_string(),
        ),
        _ => {
            let (sign, digits) = old.split_at(usize::from(old.starts_with('-')));
            let random: String = (0..digits.len())
                .map(|i| {
                    let lowest = u64::from(i == 0 && digits.len() > 1);
                    char::from(b'0' + (lowest + rng.below(10 - lowest)) as u8)
                })
                .collect();
            format!("{sign}{random}")
        }
    };
    texts[field].replace_range(start..end, &new);
    set_texts(input, texts);
}

/// Byte ranges of decimal numbers in `text`, with a minus sign that does not
/// follow a word or another number.
fn numbers(text: &str) -> Vec<(usize, usize)> {
    let bytes = text.as_bytes();
    let mut found = Vec::new();
    let mut i = 0;
    while i < bytes.len() {
        if !bytes[i].is_ascii_digit() {
            i += 1;
            continue;
        }
        let mut start = i;
        while i < bytes.len() && bytes[i].is_ascii_digit() {
            i += 1;
        }
        let glued = |at: usize| bytes[at].is_ascii_alphanumeric() || bytes[at] == b'_';
        if start > 0 && bytes[start - 1] == b'-' && (start == 1 || !glued(start - 2)) {
            start -= 1;
        }
        found.push((start, i));
    }
    found
}

/// Drops, repeats or empties an argument, or adds one if there are none.
fn change_args(input: &mut Input, rng: &mut Rng) {
    if input.args.is_empty() {
        input.args.push(pick(&EDGES, rng).to_owned());
        return;
    }
    let i = rng.below(input.args.len() as u64) as usize;
    match rng.below(3) {
        0 => drop(input.args.remove(i)),
        1 => input.args.insert(i, input.args[i].clone()),
        _ => input.args[i].clear(),
    }
}

/// Drops or repeats a line, or ends the input early; adds a number if empty.
fn change_stdin(input: &mut Input, rng: &mut Rng) {
    let text = String::from_utf8_lossy(&input.stdin).into_owned();
    if text.is_empty() {
        input.stdin = format!("{}\n", pick(&EDGES, rng)).into_bytes();
        return;
    }
    let mut lines: Vec<&str> = text.split_inclusive('\n').collect();
    let i = rng.below(lines.len() as u64) as usize;
    match rng.below(3) {
        0 => drop(lines.remove(i)),
        1 => lines.insert(i, lines[i]),
        _ => lines.truncate(i),
    }
    input.stdin = lines.concat().into_bytes();
}

/// Deletes, replaces or inserts one character of an argument or the input.
fn change_character(input: &mut Input, rng: &mut Rng) {
    let mut texts = texts(input);
    let field = rng.below(texts.len() as u64) as usize;
    let mut chars: Vec<char> = texts[field].chars().collect();
    let at = rng.below(chars.len() as u64 + 1) as usize;
    let character = pick(&CHARACTERS, rng);
    match rng.below(3) {
        0 if at < chars.len() => drop(chars.remove(at)),
        1 if at < chars.len() => chars[at] = character,
        _ => chars.insert(at, character),
    }
    texts[field] = chars.into_iter().collect();
    set_texts(input, texts);
}

#[cfg(test)]
mod tests {
    use super::*;

    fn input(args: &[&str], stdin: &str) -> Input {
        Input {
            name: "plain".to_owned(),
            args: args.iter().map(|arg| arg.to_string()).collect(),
            stdin: stdin.as_bytes().to_vec(),
        }
    }

    #[test]
    fn numbers_keep_a_leading_minus_but_not_a_hyphen() {
        let text = "-5 x-3 a12 7-2 (-40)";
        let found: Vec<&str> = numbers(text).iter().map(|&(s, e)| &text[s..e]).collect();
        assert_eq!(found, ["-5", "3", "12", "7", "2", "-40"]);
    }

    #[test]
    fn a_number_change_replaces_exactly_one_number() {
        for seed in 0..50 {
            let mut changed = input(&["12", "word"], "3 4\n");
            change_number(&mut changed, &mut Rng(seed));
            let fields = texts(&changed);
            let kept_word = fields[1] == "word";
            let differing = [("12", &fields[0]), ("3 4\n", &fields[2])]
                .iter()
                .filter(|(old, new)| old != new)
                .count();
            assert!(kept_word && differing <= 1, "{fields:?}");
        }
    }

    #[test]
    fn mutations_are_deterministic_and_keep_utf8() {
        let original = input(&["10", "ä"], "first\nsecond\n");
        let run = |seed| {
            let mut candidate = original.clone();
            let mut rng = Rng(seed);
            for _ in 0..5 {
                mutate(&mut candidate, &mut rng);
            }
            candidate
        };
        for seed in 0..100 {
            assert_eq!(run(seed), run(seed));
            assert!(String::from_utf8(run(seed).stdin).is_ok());
        }
    }

    #[test]
    fn kept_inputs_each_show_new_behaviour() {
        let dir = std::env::temp_dir().join(format!("fuzz-test-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let c_file = dir.join("g1_mod.c");
        std::fs::write(
            &c_file,
            "#include <stdio.h>\n#include <stdlib.h>\nint main(int argc, char **argv) {\n    if (argc < 2) return 2;\n    long n = strtol(argv[1], 0, 10);\n    printf(\"%ld\\n\", n % 7);\n    return 0;\n}\n",
        )
        .unwrap();
        std::fs::write(
            dir.join("g1_mod.json"),
            r#"{"inputs": [{"name": "five", "args": ["5"]}]}"#,
        )
        .unwrap();
        let kept = fuzz(&c_file, "g1_mod", &dir.join("work")).unwrap();
        let spec = eval::spec(&c_file).unwrap();
        let references = eval::References::build(&c_file, &[], &dir.join("check")).unwrap();
        let behaviours: BTreeSet<_> = spec
            .inputs
            .iter()
            .chain(&kept)
            .map(|input| {
                let run = references.check(input).unwrap();
                (run.stdout, run.exit)
            })
            .collect();
        std::fs::remove_dir_all(&dir).unwrap();
        assert!(kept.len() >= 3, "{kept:?}");
        assert_eq!(behaviours.len(), kept.len() + 1);
        assert_eq!(kept[0].name, "fuzz_1");
    }
}
